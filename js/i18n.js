  // ── helpers ───────────────────────────────────────────────────────────────
  function t(key) {
    return (T[_lang] && T[_lang][key]) || (T['en'] && T['en'][key]) || key;
  }

  function applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    document.documentElement.dir = LANGS[_lang]?.rtl ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.langBtn === _lang);
    });
    document.querySelectorAll('[data-lang-select]').forEach(sel => {
      sel.value = _lang;
    });
  }

  function set(code) {
    if (!T[code]) return;
    _lang = code;
    localStorage.setItem('lang', code);
    applyToDOM();
    if (typeof _onLangChange === 'function') _onLangChange();
    if (typeof window.onLangChange === 'function') window.onLangChange();
  }

  function buildPicker(containerId) {
    const wrap = document.getElementById(containerId);
    if (!wrap) return;
    wrap.innerHTML = '';
    Object.entries(LANGS).forEach(([code, meta]) => {
      const btn = document.createElement('button');
      btn.className = 'lang-btn';
      btn.dataset.langBtn = code;
      btn.title = meta.label;
      btn.textContent = meta.flag + ' ' + meta.label;
      if (code === _lang) btn.classList.add('active');
      btn.addEventListener('click', () => set(code));
      wrap.appendChild(btn);
    });
  }

  function buildSelect(selectId) {
    const sel = document.getElementById(selectId);
    if (!sel) return;
    sel.setAttribute('data-lang-select', '');
    sel.innerHTML = Object.entries(LANGS)
      .map(([code, meta]) =>
        `<option value="${code}"${code === _lang ? ' selected' : ''}>${meta.flag} ${meta.label}</option>`
      ).join('');
    sel.addEventListener('change', e => set(e.target.value));
  }

  // ── lang menu (dropdown in header) ───────────────────────────────────────
